"""Recurrence application code receives temporal facts, never provider timezone objects."""

from typing import Protocol

from domus.domain.recurrence_frontier import RecurrenceFrontier
from domus.domain.recurrence_records import (
    FixedProgress,
    FixedSchedule,
    ScheduledSlot,
    ScheduleState,
)
from domus.domain.recurrence_rules import FixedPattern, PeriodCandidates
from domus.domain.recurrence_time import (
    LocalInstant,
    NominalTime,
    RelativeInterval,
    ResolvedTime,
    TimePolicy,
)
from domus.domain.relative_lifecycle import RelativeClosure, RelativeEventOutcome
from domus.domain.relative_recurrence import RelativeProgress, RelativeSchedule, RelativeSlot
from domus.domain.storage import Installation
from domus.domain.task_events import TaskSourceRecord


class RecurrenceTimes(Protocol):
    @property
    def data_identity(self) -> str: ...

    def require_policy(self, policy: TimePolicy) -> None: ...

    def resolve(self, nominal: NominalTime, policy: TimePolicy) -> ResolvedTime: ...

    def local_at(self, instant_ms: int, policy: TimePolicy) -> LocalInstant: ...

    def after_local_days(
        self, performed_at: int, interval: RelativeInterval, policy: TimePolicy
    ) -> ResolvedTime: ...


class NominalExpansion(Protocol):
    def period(self, pattern: FixedPattern, index: int) -> PeriodCandidates: ...


class RecurrenceRepository(Protocol):
    @property
    def installation(self) -> Installation: ...

    def frontier(self, household_id: str) -> RecurrenceFrontier | None: ...
    def save_frontier(self, value: RecurrenceFrontier, expected_revision: int) -> None: ...

    def relative_inbox_after(self, household_id: str) -> int: ...
    def pending_relative_sources(
        self, household_id: str, *, limit: int = 100, after: int = 0
    ) -> tuple[TaskSourceRecord, ...]: ...
    def relative_sources_pending(self, household_id: str) -> bool: ...
    def next_relative_source(self, household_id: str, schedule_id: str) -> str | None: ...
    def has_current_schedule(self, household_id: str, definition_id: str) -> bool: ...
    def current_schedule_id(self, household_id: str, definition_id: str) -> str | None: ...
    def has_fixed_materialization_from(
        self, household_id: str, schedule_id: str, from_nominal: str
    ) -> bool: ...
    def fixed_slots_from(
        self, household_id: str, schedule_id: str, nominal: str
    ) -> tuple[ScheduledSlot, ...]: ...
    def has_absent_fixed_slot_from(
        self, household_id: str, schedule_id: str, nominal: str
    ) -> bool: ...
    def has_replaced_fixed_work(
        self, household_id: str, schedule_id: str, occurrence_id: str
    ) -> bool: ...
    def occurrence_is_scheduled(self, household_id: str, occurrence_id: str) -> bool: ...
    def fixed_slot_for_occurrence(
        self, household_id: str, occurrence_id: str
    ) -> ScheduledSlot | None: ...
    def maintenance_schedules(
        self, household_id: str, *, limit: int, after: str | None = None
    ) -> tuple[FixedSchedule | RelativeSchedule, ...]: ...
    def relative_source(self, household_id: str, event_key: str) -> TaskSourceRecord | None: ...
    def add_relative_source(self, record: TaskSourceRecord) -> None: ...
    def relative_source_outcome(
        self, household_id: str, event_key: str
    ) -> RelativeEventOutcome | None: ...
    def finish_relative_source(
        self, household_id: str, event_key: str, outcome: RelativeEventOutcome
    ) -> None: ...
    def relative_closure(self, household_id: str, closure_key: str) -> RelativeClosure | None: ...
    def add_relative_closure(self, value: RelativeClosure) -> None: ...

    def relative_schedule(self, household_id: str, schedule_id: str) -> RelativeSchedule | None: ...
    def relative_progress(self, household_id: str, schedule_id: str) -> RelativeProgress | None: ...
    def relative_slot(self, household_id: str, slot_key: str) -> RelativeSlot | None: ...
    def save_relative_schedule(self, value: RelativeSchedule, expected_revision: int) -> None: ...
    def save_relative_progress(self, value: RelativeProgress, expected_revision: int) -> None: ...
    def relative_slot_for_occurrence(
        self, household_id: str, occurrence_id: str
    ) -> RelativeSlot | None: ...
    def add_relative_slot(self, value: RelativeSlot) -> None: ...
    def relative_schedules(
        self,
        household_id: str,
        *,
        limit: int = 25,
        after: str | None = None,
        state: ScheduleState | None = None,
    ) -> tuple[RelativeSchedule, ...]: ...
    def relative_slots(
        self, household_id: str, schedule_id: str, *, limit: int = 25, after: str | None = None
    ) -> tuple[RelativeSlot, ...]: ...

    def schedule(self, household_id: str, schedule_id: str) -> FixedSchedule | None: ...
    def progress(self, household_id: str, schedule_id: str) -> FixedProgress | None: ...
    def slot(self, household_id: str, slot_key: str) -> ScheduledSlot | None: ...
    def save_schedule(self, value: FixedSchedule, expected_revision: int) -> None: ...
    def save_progress(self, value: FixedProgress, expected_revision: int) -> None: ...
    def add_slot(self, value: ScheduledSlot) -> None: ...
    def schedules(
        self,
        household_id: str,
        *,
        limit: int = 25,
        after: str | None = None,
        state: ScheduleState | None = None,
    ) -> tuple[FixedSchedule, ...]: ...
    def slots(
        self,
        household_id: str,
        schedule_id: str,
        *,
        limit: int = 25,
        after: str | None = None,
    ) -> tuple[ScheduledSlot, ...]: ...
