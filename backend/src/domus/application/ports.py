"""Storage contracts name household behavior rather than SQL or HTTP mechanisms."""

from contextlib import AbstractContextManager
from typing import Protocol

from domus.domain.storage import AuditEntry, CommandKey, Household, OutboxEvent, Receipt


class Households(Protocol):
    def get(self, household_id: str) -> Household | None: ...
    def current(self) -> Household | None: ...
    def save(self, household: Household, expected_revision: int) -> None: ...


class Receipts(Protocol):
    def get(self, command: CommandKey) -> Receipt | None: ...
    def get_operation(
        self, household_id: str, actor_id: str, operation_id: str
    ) -> Receipt | None: ...
    def add(self, receipt: Receipt) -> None: ...


class Audit(Protocol):
    def append(self, entry: AuditEntry) -> None: ...
    def entries(self, household_id: str) -> tuple[AuditEntry, ...]: ...


class Outbox(Protocol):
    def append(self, event: OutboxEvent) -> None: ...
    def pending(self, limit: int = 50) -> tuple[OutboxEvent, ...]: ...
    def acknowledge(self, event_id: str) -> bool: ...


class UnitOfWork(Protocol):
    @property
    def households(self) -> Households: ...
    @property
    def receipts(self) -> Receipts: ...
    @property
    def audit(self) -> Audit: ...
    @property
    def outbox(self) -> Outbox: ...


class Transactions(Protocol):
    def read(self) -> AbstractContextManager[UnitOfWork]: ...
    def write(self) -> AbstractContextManager[UnitOfWork]: ...


class CommandAuthorization(Protocol):
    def require(self, command: CommandKey, unit: UnitOfWork) -> None: ...


class Clock(Protocol):
    """UTC Unix milliseconds; domain transitions never read a global clock."""

    def now(self) -> int: ...


class Identifiers(Protocol):
    def new(self) -> str: ...
