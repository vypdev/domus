"""Storage contracts name household behavior rather than SQL or HTTP mechanisms."""

from contextlib import AbstractContextManager
from typing import Protocol

from domus.application.member_profile_ports import MemberPreferencesRepository, MemberPresentations
from domus.application.points_ports import PointsRepository
from domus.application.recurrence_ports import RecurrenceRepository
from domus.application.task_material_ports import TaskMaterialRepository
from domus.application.task_ports import TaskRepository
from domus.domain.calendar_values import (
    CalendarCandidate,
    CalendarFilters,
    CalendarPosition,
    CalendarPreference,
    CalendarRange,
)
from domus.domain.identity import HouseholdPolicy, Member
from domus.domain.recovery import RecoveryRequest
from domus.domain.storage import AuditEntry, CommandKey, Household, OutboxEvent, Receipt
from domus.domain.task_categories import TaskCategory


class Households(Protocol):
    def get(self, household_id: str) -> Household | None: ...
    def current(self) -> Household | None: ...
    def save(self, household: Household, expected_revision: int) -> None: ...


class Receipts(Protocol):
    def get(self, command: CommandKey) -> Receipt | None: ...
    def get_operation(
        self, household_id: str, actor_id: str, operation_id: str
    ) -> Receipt | None: ...
    def add(self, receipt: Receipt) -> None: ...


class Members(Protocol):
    def get(self, household_id: str, member_id: str) -> Member | None: ...
    def by_user(self, household_id: str, ha_user_id: str) -> Member | None: ...
    def list(self, household_id: str) -> tuple[Member, ...]: ...
    def save(self, member: Member, expected_revision: int) -> None: ...


class Policies(Protocol):
    def get(self, household_id: str) -> HouseholdPolicy | None: ...
    def save(self, policy: HouseholdPolicy, expected_revision: int) -> None: ...


class Recoveries(Protocol):
    def closed_before_restoration(self, household_id: str, request_id: str) -> bool: ...
    def get(self, household_id: str, request_id: str) -> RecoveryRequest | None: ...
    def pending(
        self, household_id: str, now: int, *, limit: int = 257
    ) -> tuple[RecoveryRequest, ...]: ...
    def save(self, request: RecoveryRequest, expected_revision: int) -> None: ...


class Audit(Protocol):
    def append(self, entry: AuditEntry) -> None: ...
    def entries(self, household_id: str) -> tuple[AuditEntry, ...]: ...
    def setup_actor(self, household_id: str) -> str | None:
        """The unique committed setup actor; missing is not permission to retarget."""
        ...


class Outbox(Protocol):
    def append(self, event: OutboxEvent) -> None: ...
    def pending(self, limit: int = 50) -> tuple[OutboxEvent, ...]: ...
    def acknowledge(self, event_id: str) -> bool: ...
    def delivered(self, event_id: str) -> bool | None: ...


class CalendarRepository(Protocol):
    def page(
        self,
        household_id: str,
        period: CalendarRange,
        filters: CalendarFilters,
        from_ms: int,
        until_ms: int,
        limit: int,
        after: CalendarPosition | None,
    ) -> tuple[int, int, tuple[CalendarCandidate, ...]]: ...
    def rules_pending(self, household_id: str) -> bool: ...


class CalendarPreferences(Protocol):
    def get(self, household_id: str, member_id: str) -> CalendarPreference: ...
    def save(self, preference: CalendarPreference, expected_revision: int) -> None: ...


class TaskCategories(Protocol):
    def active(self, household_id: str) -> tuple[TaskCategory, ...]: ...
    def get(self, household_id: str, category_id: str) -> TaskCategory | None: ...
    def save(self, category: TaskCategory, expected_revision: int) -> None: ...


class UnitOfWork(Protocol):
    @property
    def points(self) -> PointsRepository: ...

    @property
    def calendar_preferences(self) -> CalendarPreferences: ...

    @property
    def calendar(self) -> CalendarRepository: ...

    @property
    def presentations(self) -> MemberPresentations: ...

    @property
    def preferences(self) -> MemberPreferencesRepository: ...

    @property
    def recurrence(self) -> RecurrenceRepository: ...

    @property
    def task_materials(self) -> TaskMaterialRepository: ...

    @property
    def task_categories(self) -> TaskCategories: ...

    @property
    def tasks(self) -> TaskRepository: ...

    @property
    def households(self) -> Households: ...
    @property
    def receipts(self) -> Receipts: ...
    @property
    def audit(self) -> Audit: ...
    @property
    def outbox(self) -> Outbox: ...
    @property
    def members(self) -> Members: ...
    @property
    def policies(self) -> Policies: ...
    @property
    def recoveries(self) -> Recoveries: ...


class Transactions(Protocol):
    def read(self) -> AbstractContextManager[UnitOfWork]: ...
    def write(self) -> AbstractContextManager[UnitOfWork]: ...


class CommandAuthorization(Protocol):
    def require(self, command: CommandKey, unit: UnitOfWork) -> None: ...


class Clock(Protocol):
    """UTC Unix milliseconds; domain transitions never read a global clock."""

    def now(self) -> int: ...


class Identifiers(Protocol):
    def new(self) -> str: ...


class TimeZones(Protocol):
    """Validate an exact configured zone against the installation's timezone catalog."""

    def require(self, time_zone: str) -> None: ...
